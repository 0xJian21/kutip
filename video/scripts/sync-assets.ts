/**
 * Sync the user's files into public/ and regenerate src/manifest.generated.ts.
 *   docs/video/clips/*.{mp4,mov,webm}  → public/clips/
 *   docs/video/clips/*.log|*.txt       → public/logs/
 *   docs/video/*.mp3|*.wav|*.m4a       → public/audio/   (vo-pitch, vo-demo, vo-solami, music)
 *   docs/video/captions/*.srt|*.json   → public/captions/
 *   docs/screenshots/v2/*.png          → public/screens/
 * Durations come from Remotion's bundled ffprobe. Read-only until the copy phase; safe to re-run.
 */
import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const REPO = path.resolve(ROOT, "..");
const PUB = path.join(ROOT, "public");

const SOURCES = {
  clips: { dir: path.join(REPO, "docs/video/clips"), ext: [".mp4", ".mov", ".webm", ".m4v"], probe: true },
  logs: { dir: path.join(REPO, "docs/video/clips"), ext: [".log", ".txt"], probe: false },
  audio: { dir: path.join(REPO, "docs/video"), ext: [".mp3", ".wav", ".m4a", ".aac"], probe: true },
  captions: { dir: path.join(REPO, "docs/video/captions"), ext: [".srt", ".json"], probe: false },
  screens: { dir: path.join(REPO, "docs/screenshots/v2"), ext: [".png"], probe: false },
} as const;

type MediaInfo = { file: string; durationSec: number; width?: number; height?: number };

function probe(file: string): Omit<MediaInfo, "file"> {
  try {
    const out = execFileSync("pnpm", ["exec", "remotion", "ffprobe", "-v", "error", "-show_entries", "format=duration:stream=width,height", "-of", "json", file], { cwd: ROOT, encoding: "utf8" });
    const j = JSON.parse(out) as { format?: { duration?: string }; streams?: Array<{ width?: number; height?: number }> };
    const v = j.streams?.find((s) => s.width);
    return { durationSec: Number(j.format?.duration ?? 0), width: v?.width, height: v?.height };
  } catch {
    return { durationSec: 0 };
  }
}

const list = (dir: string, ext: readonly string[]) => (existsSync(dir) ? readdirSync(dir).filter((f) => ext.includes(path.extname(f).toLowerCase()) && statSync(path.join(dir, f)).isFile()).sort() : []);

const manifest: { syncedAt: string; clips: MediaInfo[]; audio: MediaInfo[]; screens: string[]; captions: string[]; logs: string[] } = { syncedAt: new Date().toISOString(), clips: [], audio: [], screens: [], captions: [], logs: [] };

for (const [key, src] of Object.entries(SOURCES) as Array<[keyof typeof SOURCES, (typeof SOURCES)[keyof typeof SOURCES]]>) {
  const files = list(src.dir, src.ext);
  const dest = path.join(PUB, key);
  mkdirSync(dest, { recursive: true });
  for (const f of files) {
    const from = path.join(src.dir, f);
    const to = path.join(dest, f);
    if (!existsSync(to) || statSync(to).mtimeMs < statSync(from).mtimeMs) copyFileSync(from, to);
    if (key === "clips" || key === "audio") manifest[key].push({ file: f, ...probe(from) });
    else manifest[key].push(f);
  }
  console.log(`${key.padEnd(9)} ${files.length} file(s)${files.length ? ": " + files.join(", ") : ""}`);
}

const header = `// Generated by \`pnpm sync\` (scripts/sync-assets.ts) on ${manifest.syncedAt}. Do not edit by hand.
// Lists the files currently in public/ so compositions can fall back to a slate when a file is missing.
export type MediaInfo = { file: string; durationSec: number; width?: number; height?: number };
export const MANIFEST = {
  syncedAt: ${JSON.stringify(manifest.syncedAt)} as string | null,
  clips: ${JSON.stringify(manifest.clips, null, 2)} as MediaInfo[],
  audio: ${JSON.stringify(manifest.audio, null, 2)} as MediaInfo[],
  screens: ${JSON.stringify(manifest.screens)} as string[],
  captions: ${JSON.stringify(manifest.captions)} as string[],
  logs: ${JSON.stringify(manifest.logs)} as string[],
};
`;
writeFileSync(path.join(ROOT, "src/manifest.generated.ts"), header);
console.log("wrote src/manifest.generated.ts");
